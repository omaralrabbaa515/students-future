import { certifications } from "@/data/certifications";
import { majors } from "@/data/majors";
import { universities } from "@/data/universities";

const certificationsCatalog = certifications
  .map(
    (c) =>
      `• [${c.title}](${c.url}) | الجهة المانحة: ${c.provider} | التصنيف: ${c.category} | نبذة: ${c.summary} | طريقة الحصول: ${c.howToGet}`,
  )
  .join("\n");

const majorsCatalog = majors
  .map(
    (m) =>
      `• ${m.name} (${m.field}): التصنيف: [${m.classification}]، نسبة التشغيل: [${m.employmentRate}]، الخطر: [${m.risk}]، الأتمتة: [${m.automation.exposure}] - ${m.automation.note}، جامعات حكومية: [${m.publicUniversities.slice(0, 4).join("، ")}]، اعتمادات: [${m.accreditation}]${
        m.alternatives && m.alternatives.length > 0
          ? `، البدائل الموصى بها: ${m.alternatives.map((a) => `${a.name} (${a.reason})`).join("، ")}`
          : ""
      }`,
  )
  .join("\n");

const universitiesCatalog = universities
  .map(
    (u) =>
      `• ${u.name} (${u.englishName}) [نوع: ${u.type}، موقع: ${u.location.city} - ${u.location.region}]: تصنيف: [${u.rankingSummary}]، كليات رائدة: [${u.flagshipColleges.join("، ")}]، اعتمادات دولية: [${u.internationalAccreditations.join("، ")}]، ما يميزها: [${u.uniqueAdvantages.slice(0, 3).join("؛ ")}]، متى يختارها الطالب: [${u.advisorRecommendation}]`,
  )
  .join("\n");

